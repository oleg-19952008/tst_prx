    private static byte[] RefEncode(ReadOnlySpan<byte> data)
    {
        var bits = new List<int>();
        foreach (byte b in data)
        {
            (_, uint code, int len) = Table[b];
            for (int i = len - 1; i >= 0; i--)
                bits.Add((int)((code >> i) & 1));
        }
        while (bits.Count % 8 != 0) bits.Add(1); // EOS padding
        var outBytes = new byte[bits.Count / 8];
        for (int i = 0; i < bits.Count; i++)
            if (bits[i] != 0) outBytes[i / 8] |= (byte)(0x80 >> (i % 8));
        return outBytes;
    }

    public static List<Case> Run()
    {
        var cases = new List<Case>();

        void Check(string name, Func<string> body)
        {
            try { cases.Add(new Case(name, true, body())); }
            catch (Exception ex) { cases.Add(new Case(name, false, ex.Message)); }
        }

        // ---- Positive: RFC 7541 Appendix C literal Huffman vectors ----
        Check("C.4.1 www.example.com", () =>
        {
            var got = HpackHuffman.DecodeAscii(Convert.FromHexString("f1e3c2e5f23a6baac8d29aee2b0b0f3f"));
            Eq(got, "www.example.com"); return $"decoded \"{got}\"";
        });
        Check("C.4.2 no-cache", () =>
        {
            var got = HpackHuffman.DecodeAscii(Convert.FromHexString("a8eb10649cbf"));
            Eq(got, "no-cache"); return $"decoded \"{got}\"";
        });
        Check("C.4.3 custom-key", () =>
        {
            var got = HpackHuffman.DecodeAscii(Convert.FromHexString("25a849e95bb27f"));
            Eq(got, "custom-key"); return $"decoded \"{got}\"";
        });
        Check("C.4.3 custom-value", () =>
        {
            var got = HpackHuffman.DecodeAscii(Convert.FromHexString("25a849e95bb8e8b48b812dcd"));
            Eq(got, "custom-value"); return $"decoded \"{got}\"";
        });
        Check("C.6.1 status 302", () =>
        {
            var got = HpackHuffman.DecodeAscii(Convert.FromHexString("640c51"));
            Eq(got, "302"); return $"decoded \"{got}\"";
        });
        Check("C.6.1 cache-control private", () =>
        {
            var got = HpackHuffman.DecodeAscii(Convert.FromHexString("aec3771a4b"));
            Eq(got, "private"); return $"decoded \"{got}\"";
        });
        Check("C.6.1 date", () =>
        {
            var got = HpackHuffman.DecodeAscii(Convert.FromHexString("d07abe94e154d68bbaa6cf509e"));
            Eq(got, "Mon, 21 Oct 2013 20:13:21 GMT"); return $"decoded \"{got}\"";
        });
        Check("C.6.1 location", () =>
        {
            var got = HpackHuffman.DecodeAscii(Convert.FromHexString("9d29ad171863c78f0b97c8e9ae82ca"));
            Eq(got, "https://www.example.com"); return $"decoded \"{got}\"";
        });
        Check("C.6.2 status 307", () =>
        {
            var got = HpackHuffman.DecodeAscii(Convert.FromHexString("640e441d"));
            Eq(got, "307"); return $"decoded \"{got}\"";
        });
        Check("C.6.2 content-encoding gzip", () =>
        {
            var got = HpackHuffman.DecodeAscii(Convert.FromHexString("9bd9ab"));
            Eq(got, "gzip"); return $"decoded \"{got}\"";
        });
        Check("C.6.3 set-cookie", () =>
        {
            var hex = "f2b458d6dc5fd78e90e7f0ed5f87dbc929b7eed599f45a4b2a91d59029c2ef7b";
            var got = HpackHuffman.DecodeAscii(Convert.FromHexString(hex));
            Eq(got, "foo=ASDJKHQKBZXOQWEOPIUAXQWEOIU; max-age=3600; version=1");
            return $"decoded \"{got}\"";
        });

        // ---- Round-trip: every single byte 0..255 ----
        Check("roundtrip-all-256-bytes", () =>
        {
            for (int b = 0; b < 256; b++)
            {
                var data = new byte[] { (byte)b };
                var buf = new byte[HpackHuffman.EncodedLength(data)];
                int n = HpackHuffman.Encode(data, buf);
                var back = HpackHuffman.Decode(buf.AsSpan(0, n));
                if (back.Length != 1 || back[0] != (byte)b)
                    throw new Exception($"roundtrip failed for byte {b}");
            }
            return "256/256 bytes round-tripped";
        });

        // ---- Round-trip: long mixed string ----
        Check("roundtrip-mixed-long", () =>
        {
            var sb = new StringBuilder();
            var rnd = new Random(12345);
            for (int i = 0; i < 4096; i++) sb.Append((char)rnd.Next(0, 256));
            var data = Encoding.UTF8.GetBytes(sb.ToString());
            var buf = new byte[HpackHuffman.EncodedLength(data)];
            int n = HpackHuffman.Encode(data, buf);
            var back = HpackHuffman.Decode(buf.AsSpan(0, n), maxOutputBytes: 1 << 20);
            if (!back.AsSpan().SequenceEqual(data)) throw new Exception("mismatch");
            return $"{data.Length} bytes round-tripped";
        });

        // ---- Padding 0..7 one-bits accepted ----
        Check("padding-0-to-7-ones", () =>
        {
            // 'www' encodes to 18 bits; append k extra 1-bits (k=0..7) as padding.
            for (int k = 0; k <= 7; k++)
            {
                var bits = new List<int>();
                foreach (byte b in "www"u8)
                {
                    (_, uint code, int len) = Table[b];
                    for (int i = len - 1; i >= 0; i--) bits.Add((int)((code >> i) & 1));
                }
                for (int j = 0; j < k; j++) bits.Add(1);
                int padTo = ((bits.Count + 7) / 8) * 8;
                for (int j = bits.Count; j < padTo; j++) bits.Add(0); // zero fill beyond padding
                var bs = new byte[padTo / 8];
                for (int i = 0; i < padTo; i++)
                    if (bits[i] != 0) bs[i / 8] |= (byte)(0x80 >> (i % 8));
                var got = Encoding.ASCII.GetString(HpackHuffman.Decode(bs));
                if (got != "www") throw new Exception($"padding {k}: got \"{got}\"");
            }
            return "padding 0..7 ones accepted";
        });

        // ---- Empty input -> empty output ----
        Check("empty-input", () =>
        {
            var got = HpackHuffman.Decode(ReadOnlySpan<byte>.Empty);
            if (got.Length != 0) throw new Exception("expected empty");
            return "empty -> empty";
        });

        // ---- Negative tests ----
        Check("neg-padding-8-ones", () =>
        {
            // 'w' = 0xf (4 bits) then 8 one-bits of padding (invalid: >7 bits).
            // Bits: 1111 1111 1111 -> bytes f f c0? Construct explicitly:
            // w(1111) + 11111111 + zeros to byte boundary = 12 bits -> 2 bytes.
            var bits = "1111" + "11111111" + "0"; // 13 bits, pad last byte with 0
            var bs = FromBitString(bits);
            ExpectThrow(bs, "8-bit all-ones padding");
            return "threw as expected";
        });
        Check("neg-padding-with-zero-bit", () =>
        {
            // 'w'(1111) + '1'-bit padding that contains a 0 before boundary: 1111 1101
            var bs = FromBitString("11111101");
            ExpectThrow(bs, "padding containing zero bit");
            return "threw as expected";
        });
        Check("neg-full-eos", () =>
        {
            // ff ff ff bf = 30 ones + 0-pad == full EOS code -> must throw EOS error.
            ExpectThrow(Convert.FromHexString("ffffffbf"), "full EOS sequence");
            return "threw as expected";
        });
        Check("neg-truncated-code", () =>
        {
            // A prefix of a longer symbol that ends in a 0 bit and is not decodable:
            // take 'a'(00000,5) then '1'(00001,5): 00000 00001 -> decode ok ("a1").
            // Instead craft invalid: 5-bit code '00000'(a) + dangling '010' (not a
            // valid partial path ending only in ones) -> expect throw.
            ExpectThrow(FromBitString("00000010"), "truncated non-one padding");
            return "threw as expected";
        });
        Check("neg-max-output", () =>
        {
            var data = Encoding.ASCII.GetBytes("aaaaaaaaaaaaaaaaaaaa"); // 20 chars
            var buf = new byte[HpackHuffman.EncodedLength(data)];
            int n = HpackHuffman.Encode(data, buf);
            try
            {
                HpackHuffman.Decode(buf.AsSpan(0, n), maxOutputBytes: 8);
            }
            catch (Exception ex) when (ex.GetType().Name == "HpackException") { return "threw bound error as expected"; }
            throw new Exception("expected HpackException for maxOutputBytes=8");
        });

        // ---- EncodedLength matches actual Encode output size ----
        Check("encodedlength-matches-encode", () =>
        {
            foreach (var s in new[] { "", "www.example.com", "no-cache", "custom-key", "a;~\x00\xff" })
            {
                var data = Encoding.UTF8.GetBytes(s);
                int expected = HpackHuffman.EncodedLength(data);
                var buf = new byte[Math.Max(expected, 1)];
                int n = data.Length == 0 ? 0 : HpackHuffman.Encode(data, buf);
                if (n != expected) throw new Exception($"\"{s}\": EncodedLength={expected}, Encode={n}");
            }
            return "EncodedLength == Encode size for all probes";
        });

        return cases;
    }

    private static void Eq(string got, string want)
    {
        if (got != want) throw new Exception($"got \"{got}\", want \"{want}\"");
    }

    private static byte[] FromBitString(string bits)
    {
        int pad = (8 - bits.Length % 8) % 8;
        bits += new string('0', pad);
        var bs = new byte[bits.Length / 8];
        for (int i = 0; i < bits.Length; i++)
            if (bits[i] == '1') bs[i / 8] |= (byte)(0x80 >> (i % 8));
        return bs;
    }

    private static void ExpectThrow(byte[] src, string label)
    {
        try
        {
            var got = HpackHuffman.Decode(src);
            throw new Exception($"{label}: expected HpackException, decoded \"{Encoding.ASCII.GetString(got)}\"");
        }
        catch (Exception ex) when (ex.GetType().Name == "HpackException")
        {
            // expected — HpackException is internal, matched by type name
        }
    }
}
