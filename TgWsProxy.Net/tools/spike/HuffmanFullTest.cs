// Full RFC 7541 Huffman self-test suite (Appendix C vectors + negative cases).
// Runs inside SpikeTransport so it executes on every spike invocation without a
// separate xUnit toolchain. The reference table here is an INDEPENDENT copy of
// RFC 7541 Appendix B, canonically regenerated from the code words themselves
// (code word -> its MSB-aligned bit string), so it cannot inherit any typo in
// the product tables — it cross-checks both EncodeCodes and EncodeLengths.
using System.Text;
using TgWsProxy.Transport.H2;

internal static class HuffmanFullTest
{
    public sealed record Case(string Name, bool Ok, string Detail);

    // ---- Independent canonical table: (symbol, code, length) per RFC 7541 App. B ----
    private static readonly (int Sym, uint Code, int Len)[] Table = BuildCanonical();

    private static (int, uint, int)[] BuildCanonical()
